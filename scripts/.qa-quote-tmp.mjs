import puppeteer from "puppeteer-core";
const OUT = process.env.OUT;
const W = Number(process.env.W ?? 390);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const b = await puppeteer.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: "new" });
const p = await b.newPage();
await p.setViewport({ width: W, height: 900, deviceScaleFactor: 1 });
const logs = [];
p.on("console", (m) => { if (m.type() === "error" || m.type()==="warn") logs.push(m.type()+": "+m.text().slice(0, 300)); });
p.on("pageerror", (e) => logs.push("PAGEERROR " + e.message));
await p.goto("http://localhost:8089/sign-in", { waitUntil: "networkidle2", timeout: 180000 });
await p.waitForSelector("[role=combobox]", { timeout: 60000 });
await p.click("[role=combobox]"); await sleep(500);
(await p.$$("[role=menuitem]"))[0].click();
await p.waitForFunction(() => location.pathname !== "/sign-in", { timeout: 60000 }); await sleep(4000);
const clickText = async (re) => p.evaluate((src) => { const r = new RegExp(src, "i"); const els = [...document.querySelectorAll('[role=button],[role=radio],[role=link],[tabindex]')].filter(e => r.test(e.getAttribute('aria-label')||'') || r.test(e.textContent||'')); const e = els[els.length-1]; if (e) { e.click(); return (e.getAttribute('aria-label')||e.textContent).slice(0,80); } return null; }, re);
const text = () => p.evaluate(() => document.body.innerText.slice(0, 3000));
const shot = (n) => p.screenshot({ path: `${OUT}/${n}@${W}.png`, fullPage: true });
await p.evaluate(() => { window.history.pushState({}, "", "/quote/product"); window.dispatchEvent(new PopStateEvent("popstate")); }); await sleep(4000);
console.log("URL", await p.evaluate(() => location.pathname));
const steps = (process.env.STEPS ?? "").split("|").filter(Boolean);
for (const s of steps) { if (s.startsWith("shot:")) { await shot(s.slice(5)); console.log("shot", s); continue; } if (s.startsWith("see:")) { await p.evaluate((src)=>{const r=new RegExp(src,"i"); const e=[...document.querySelectorAll("div,[role]")].reverse().find(e=>r.test(e.getAttribute("aria-label")||"")||(e.children.length===0&&r.test(e.textContent||""))); e?.scrollIntoView({block:"center"});}, s.slice(4)); await sleep(800); continue; } const r = s.startsWith("wait") ? (await sleep(Number(s.slice(4))), "waited") : await clickText(s); console.log("click", s, "->", r); await sleep(3000); }
console.log("URL", await p.evaluate(() => location.pathname));
console.log(await text());
await shot(process.env.NAME ?? "q");
console.log(logs.slice(-20).join("\n"));
await b.close();
